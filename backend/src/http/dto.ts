import type { CompetitorRow, FieldChange, SnapshotRow, SnapshotStatus, SummaryStatus } from "../db/schema.js";

export type CompetitorDto = {
  id: string;
  createdAt: string;
  lastPolledAt: string | null;
  lastStatus: SnapshotStatus | null;
  lastChangedAt: string | null;
  changedInLast24h: boolean;
  nextPollAt: string;
  /** Current adaptive polling interval; grows while nothing changes, resets on a change. */
  intervalSeconds: number;
  unchangedStreak: number;
};

export type SnapshotDto = {
  id: number;
  fetchedAt: string;
  status: SnapshotStatus;
  title: string | null;
  tagline: string | null;
  price: string | null;
  description: string | null;
  /** Fields the source did not return in this poll; their values are carried forward. */
  missingFields: string[];
  /** Why the poll failed, when status is 'error'. */
  error: string | null;
  changed: boolean;
  changes: FieldChange[];
  summary: string | null;
  summaryStatus: SummaryStatus;
  /** Human-readable explanation of summaryStatus, for the UI. */
  summaryReason: string;
  summarySource: "llm" | "rule" | null;
};

const DAY_MS = 24 * 60 * 60 * 1000;

export function toCompetitorDto(row: CompetitorRow, intervalSeconds: number, now = new Date()): CompetitorDto {
  return {
    id: row.id,
    createdAt: row.createdAt.toISOString(),
    lastPolledAt: row.lastPolledAt?.toISOString() ?? null,
    lastStatus: row.lastStatus,
    lastChangedAt: row.lastChangedAt?.toISOString() ?? null,
    changedInLast24h: row.lastChangedAt !== null && now.getTime() - row.lastChangedAt.getTime() < DAY_MS,
    nextPollAt: row.nextPollAt.toISOString(),
    intervalSeconds,
    unchangedStreak: row.unchangedStreak,
  };
}

export function summaryReason(row: SnapshotRow): string {
  switch (row.summaryStatus) {
    case "ok":
      return row.summarySource === "rule" ? "Generated by a rule; no LLM call was needed." : "Generated by the LLM.";
    case "pending":
      return row.summaryError
        ? `A change was detected; the summary is queued: ${row.summaryError}.`
        : "A change was detected; the summary is being generated.";
    case "failed":
      return `The LLM call failed after ${row.summaryAttempts} attempt(s)${row.summaryError ? `: ${row.summaryError}` : "."}`;
    case "unusable":
      return `The LLM answered, but the answer was unusable${row.summaryError ? `: ${row.summaryError}` : "."}`;
    case "cap_reached":
      return "The daily LLM call cap was reached; no summary was generated.";
    case "disabled":
      return "No LLM is configured.";
    case "not_needed":
      return row.status === "not_found"
        ? "Still not listed at the source."
        : "Nothing that matters changed since the previous snapshot.";
    case "no_previous":
      return row.status === "not_found"
        ? "First poll: the source does not know this id, or it is delisted right now. Polling continues."
        : "First snapshot of this competitor; nothing to compare with.";
    case "poll_failed":
      return "The poll failed, so there is no listing to compare.";
  }
}

export function toSnapshotDto(row: SnapshotRow): SnapshotDto {
  return {
    id: row.id,
    fetchedAt: row.fetchedAt.toISOString(),
    status: row.status,
    title: row.title,
    tagline: row.tagline,
    price: row.price,
    description: row.description,
    missingFields: row.missingFields,
    error: row.error,
    changed: row.changed,
    changes: row.changes ?? [],
    summary: row.summary,
    summaryStatus: row.summaryStatus,
    summaryReason: summaryReason(row),
    summarySource: (row.summarySource as "llm" | "rule" | null) ?? null,
  };
}
